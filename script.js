// Switch Active Pages
function showPage(pageId) {
    const pages = document.querySelectorAll('.page-content');
    pages.forEach(page => page.classList.remove('active'));

    const navLinks = document.querySelectorAll('.nav-link');
    navLinks.forEach(link => link.classList.remove('active'));

    const targetPage = document.getElementById('page-' + pageId);
    if (targetPage) {
        targetPage.classList.add('active');
    }

    const activeNav = document.getElementById('nav-' + pageId);
    if (activeNav) {
        activeNav.classList.add('active');
    }

    window.scrollTo({ top: 0, behavior: 'smooth' });
    setTimeout(initScrollReveal, 50);
}

// Search Filter Functionality
function filterParts(pageType) {
    let inputId = '';
    let parentSelector = '';

    if (pageType === 'power-sprayer') {
        inputId = 'search-power';
        parentSelector = '#page-power-sprayer .part-card';
    } else if (pageType === 'htp-pump') {
        inputId = 'search-htp';
        parentSelector = '#page-htp-pump .part-card';
    } else if (pageType === 'battery-pump') {
        inputId = 'search-battery';
        parentSelector = '#page-battery-pump .part-card';
    }

    const filter = document.getElementById(inputId).value.toLowerCase();
    const cards = document.querySelectorAll(parentSelector);

    cards.forEach(card => {
        const text = card.textContent || card.innerText;
        card.style.display = text.toLowerCase().includes(filter) ? "" : "none";
    });
}

// Scroll Reveal Observer
function initScrollReveal() {
    const observer = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                entry.target.classList.add('visible');
            }
        });
    }, { threshold: 0.1 });

    const revealElements = document.querySelectorAll('.feature-card, .category-card, .banner-cta, .c-card');
    revealElements.forEach(el => {
        el.classList.add('reveal-on-scroll');
        observer.observe(el);
    });
}

